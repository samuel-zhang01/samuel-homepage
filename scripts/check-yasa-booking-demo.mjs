import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
const path = new URL('../src/lib/yasaBookingDemo.ts', import.meta.url);
const compiled = ts.transpileModule(readFileSync(path, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const evaluated = { exports: {} };
runInNewContext(compiled, { module: evaluated, exports: evaluated.exports, TextEncoder, Date, Intl });
const { yasaSlots, yasaDateKey, yasaCalendar, validateYasaGuest } = evaluated.exports;
const config = { mode: 'collective', duration: 45, buffer: 15, required: ['alex', 'morgan'], event: 'review' };
const guest = { name: 'Jamie Taylor', email: 'jamie@example.invalid', company: 'Example', topic: 'Project feedback', notes: '', reminder: true };
const slots = yasaSlots(config, [], 'Europe/London');
const optionalBusy = slots.find(s => s.free && s.optionalAvailable === 0);
const suggested = slots.find(s => s.free && s.optionalAvailable === 1 && s.preferred);
assert.ok(optionalBusy, 'optional unavailability must not prevent a required-host meeting');
assert.ok(suggested, 'optional host availability produces suggestions');
assert.equal(optionalBusy.optionalIds.join(), 'riley');
assert.equal(optionalBusy.hostIds.join(), 'alex,morgan');
const allRequired = yasaSlots({ ...config, required: ['alex', 'morgan', 'riley'] }, [], 'Europe/London');
assert.equal(allRequired.find(s => s.start === optionalBusy.start)?.free, false, 'promoting the unavailable optional host blocks this time');
const booking = { id: 'fixture-one', config, slot: optionalBusy, guest, timezone: 'Europe/London', status: 'confirmed' };
assert.equal(yasaSlots(config, [booking], 'Europe/London').find(s => s.start === booking.slot.start)?.free, false, 'confirmed required-host booking occupies its slot');
assert.equal(yasaSlots(config, [{ ...booking, status: 'cancelled' }], 'Europe/London').find(s => s.start === booking.slot.start)?.free, true, 'cancellation releases the time');
assert.equal(yasaSlots(config, [booking], 'Europe/London', booking.id).find(s => s.start === booking.slot.start)?.free, true, 'rescheduling can retain its own original time');
const optionalInvite = { ...booking, slot: suggested };
const single = { mode: 'round-robin', duration: 45, buffer: 15, required: ['alex', 'morgan', 'riley'], event: 'chat' };
const optionalStillFree = yasaSlots(single, [optionalInvite], 'Europe/London').find(s => s.start === suggested.start);
assert.equal(optionalStillFree?.free, true, 'inviting Riley optionally does not reserve Riley');
assert.equal(optionalStillFree?.hostIds.join(), 'riley');
const movedSlot = slots.find(s => s.free && s.start !== booking.slot.start && new Date(s.start).getTime() >= new Date(booking.slot.end).getTime() + 30 * 60000);
const successor = { ...booking, id: 'fixture-two', slot: movedSlot, previousId: booking.id };
const afterMove = [{ ...booking, status: 'rescheduled' }, successor];
assert.equal(yasaSlots(config, afterMove, 'Europe/London').find(s => s.start === booking.slot.start)?.free, true, 'confirmed successor releases predecessor');
assert.equal(yasaSlots(config, afterMove, 'Europe/London').find(s => s.start === successor.slot.start)?.free, false, 'successor occupies its required hosts');
assert.equal(yasaDateKey('2026-11-16T16:15:00Z', 'Europe/London'), '2026-11-16');
assert.equal(yasaDateKey('2026-11-16T16:15:00Z', 'Asia/Tokyo'), '2026-11-17', 'Tokyo availability must be grouped under next-day guest date');
assert.equal(validateYasaGuest({ ...guest, email: 'wrong' }), 'email');
assert.equal(validateYasaGuest({ ...guest, name: '' }), 'name');
assert.equal(validateYasaGuest({ ...guest, topic: 'unknown' }), 'topic');
assert.equal(validateYasaGuest(guest), null);
const calendar = yasaCalendar(optionalInvite, 'Team review');
const unfolded = calendar.replace(/\r\n /g, '');
assert.ok(unfolded.includes(`DTSTART:${suggested.start.replace(/[-:]/g, '').replace(/\.000Z/, 'Z')}`));
assert.ok(unfolded.includes('ATTENDEE;ROLE=OPT-PARTICIPANT;PARTSTAT=NEEDS-ACTION;RSVP=TRUE;CN="riley":mailto:riley@example.invalid'));
assert.ok(unfolded.includes('BEGIN:VALARM'));
const cancellation = yasaCalendar(optionalInvite, 'Team review', true);
assert.ok(cancellation.includes('METHOD:CANCEL\r\n'));
assert.ok(cancellation.includes('UID:fixture-one@example.invalid\r\n'));
assert.ok(cancellation.includes('STATUS:CANCELLED\r\n'));
assert.ok(!cancellation.includes('BEGIN:VALARM'));
const unicode = yasaCalendar({ ...optionalInvite, guest: { ...guest, name: '測試來賓'.repeat(15) } }, '会議, notes; on\\time\nnext');
for (const line of unicode.split('\r\n')) assert.ok(new TextEncoder().encode(line).length <= 75, 'ICS physical lines are folded by UTF-8 byte length');
assert.ok(unicode.replace(/\r\n /g, '').includes('SUMMARY:会議\\, notes\\; on\\\\time\\nnext'));
console.log('YASA booking model: required/optional host decisions, weighted assignment, occupancy/release, linked reschedule, guest-local day rollover, typed guest validation and role-aware UTC ICS passed.');
