function toTraditionalMandarin(value: string): string {
  let translated = value;
  for (const [simplified, traditional] of traditionalPhrases) {
    translated = translated.replaceAll(simplified, traditional);
  }
  return [...translated].map((character) => traditionalChars[character] ?? character).join("");
}

function toAmericanEnglish(value: string): string {
  const protectedFirstClass = value.replaceAll("First-Class Honours", "__FIRST_CLASS_HONOURS__");
  return protectedFirstClass
    .replaceAll("__FIRST_CLASS_HONOURS__", "First-Class Honours")
    .replaceAll("judgement", "judgment")
    .replaceAll("behaviour", "behavior")
    .replaceAll("modelling", "modeling")
    .replaceAll("organised", "organized")
    .replaceAll("organisational", "organizational")
    .replaceAll("prioritisation", "prioritization")
    .replaceAll("recognisably", "recognizably")
    .replaceAll("centre", "center")
    .replaceAll("programme", "program")
    .replaceAll("CV", "resume")
    .replaceAll("Résumé", "Resume");
}

function preserveWhitespace(source: string, translated: string): string {
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

export function translateText(locale: Locale, source: string): string {
  const compact = source.replace(/\s+/g, " ").trim();
  if (!compact || locale === "en-GB") return source;
  if (locale === "en-US") {
    return preserveWhitespace(source, usOverrides[compact] ?? toAmericanEnglish(compact));
  }
  const simplified = zhCN[compact] ?? compact;
  const translated = locale === "zh-TW" ? toTraditionalMandarin(simplified) : simplified;
  return preserveWhitespace(source, translated);
}

export function normaliseLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  const lower = value.toLowerCase();
  if (lower === "en-gb" || lower === "en_uk" || lower === "uk") return "en-GB";
  if (lower === "en-us" || lower === "en_us" || lower === "us") return "en-US";
  if (lower === "zh-cn" || lower === "zh-hans" || lower === "zh_cn") return "zh-CN";
  if (lower === "zh-tw" || lower === "zh-hant" || lower === "zh_tw") return "zh-TW";
  return null;
}

export function localeSlug(locale: Locale): string {
  return localeOptions.find((option) => option.locale === locale)?.slug ?? "en-gb";
}
